x=int(input('Enter Num1:'))
y=int(input('Enter Num2:'))

def add(a,b):
    return a+b
print('addition=',add(x,y))

def sub(a,b):
    return a-b
print('subtraction=',sub(x,y))

def mul(a,b):
    return a*b
print('multiply=',mul(x,y))

def div(a,b):
    return a/b
print('division=',div(x,y))





